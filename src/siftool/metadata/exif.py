"""EXIF/TIFF reading, per-tag privacy categories, and a minimal EXIF writer.

`parse_exif` walks a TIFF byte blob (the payload of a JPEG APP1 "Exif"
segment, or a bare TIFF file) and returns one `Finding` per tag, tagged
with the `Category` a privacy mode can whitelist. `build_minimal_exif`
writes a brand-new, minimal big-endian TIFF containing only the tags
whose category is allowed -- used to keep e.g. `Orientation` while
dropping GPS. `strip_exif_header` removes the optional `Exif\\x00\\x00`
prefix some containers (JPEG APP1) put before the TIFF bytes.

Every tag not covered by `TAG_CATEGORIES` (or the GPS/Interop IFDs, which
have their own rules) is `Category.UNKNOWN`, labelled `f"Tag 0x{tag:04X}"`.
A fixed set of *structural* tags -- the sub-IFD pointers, the thumbnail
offset/length, and `ExifVersion` (generated by `build_minimal_exif` itself)
-- never produce a tag `Finding` (ruling R6).

Sub-IFD pointers (ExifIFD, GPS, Interop) are followed in every form a
classic TIFF allows -- `LONG`, `SHORT` or `IFD` (type 13, TIFF Tech Note
1), count 1 -- wherever they appear. A pointer that cannot be followed
(any other type or count, an offset out of bounds, a loop, a sub-IFD that
cannot be read) becomes `Finding(UNKNOWN, "Unfollowed sub-IFD pointer")`
instead of being silently skipped, so a block holding one never reads as
all-allowed (ruling R18). TIFF forbids repeating a tag in one IFD: every
repeat after the first becomes `Finding(UNKNOWN, "Duplicate tag 0x....")`
instead of a second description of the tag, so a block holding one never
reads as all-allowed either (ruling R24).

`build_minimal_exif` keeps an allowed tag only in its Exif-standard type
and count (`STANDARD_FORMS`, ruling R18), only from its first entry in
each IFD (ruling R24), and writes it canonically:
big-endian, ASCII cut at its first NUL, sorted entries, fresh pointers and
`ExifVersion`. Its output is therefore a fixed point
(`build_minimal_exif(build_minimal_exif(x, a), a) == build_minimal_exif(x,
a)`), which keeps a second clean byte-identical even though every EXIF
block is rewritten on every clean.

Robustness is a hard requirement: malformed input (bad offsets, IFD
loops, oversized entry counts, truncated values) must never raise, and a
huge value array costs no more than its first `_MAX_DETAIL_VALUES` values
to describe (review M5). Every public function bottoms out in a broad
`except Exception` that degrades to a single `Finding` (`parse_exif`) or
`None` (`build_minimal_exif`).
"""

