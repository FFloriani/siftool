def _resolve(ifd_name: str, tag: int) -> tuple[str, Category]:
    """Return `(label, category)` for `tag` found while parsing `ifd_name`.

    IFD0/ExifIFD tags fall back to the other main IFD's table when absent
    from their own (addendum rule); GPS tags are always `LOCATION`;
    Interop tags are always `UNKNOWN`. Anything still unmatched is
    `UNKNOWN`, labelled `f"Tag 0x{tag:04X}"`.
    """
    if ifd_name == "GPS":
        return _GPS_TAG_NAMES.get(tag, f"Tag 0x{tag:04X}"), Category.LOCATION
    if ifd_name == "Interop":
        return f"Tag 0x{tag:04X}", Category.UNKNOWN
    primary = _IFD0_TAGS if ifd_name == "IFD0" else _EXIF_IFD_TAGS
    fallback = _EXIF_IFD_TAGS if ifd_name == "IFD0" else _IFD0_TAGS
    if tag in primary:
        return primary[tag]
    if tag in fallback:
        return fallback[tag]
    return f"Tag 0x{tag:04X}", Category.UNKNOWN


class _Corrupt(Exception):
    """Raised internally on any structural problem; never escapes this module."""


def _check(buf: bytes, offset: int, length: int) -> None:
    if offset < 0 or length < 0 or offset + length > len(buf):
        raise _Corrupt(f"out of bounds: offset={offset} length={length} buf={len(buf)}")


def _u16(buf: bytes, offset: int, order: str) -> int:
    return struct.unpack_from(order + "H", buf, offset)[0]


def _u32(buf: bytes, offset: int, order: str) -> int:
    return struct.unpack_from(order + "I", buf, offset)[0]


def _read_header(tiff: bytes) -> tuple[str, int]:
    """Return `(byte_order, ifd0_offset)`, or raise `_Corrupt`."""
    _check(tiff, 0, 8)
    bom = tiff[0:2]
    if bom == b"II":
        order = "<"
    elif bom == b"MM":
        order = ">"
    else:
        raise _Corrupt(f"bad byte order mark: {bom!r}")
    if _u16(tiff, 2, order) != 0x2A:
        raise _Corrupt("bad TIFF magic number")
    return order, _u32(tiff, 4, order)


def _read_ifd_header(buf: bytes, offset: int, order: str, visited: set[int]) -> tuple[int, int, int]:
    """Bounds-check `offset` as an IFD header; return `(entries_start, count, next_offset)`.

    Marks `offset` visited (raising `_Corrupt` if already visited, which
    is how IFD loops are detected) and rejects more than `_MAX_ENTRIES`.
    """
    if offset in visited:
        raise _Corrupt(f"IFD loop at offset {offset}")
    visited.add(offset)
    _check(buf, offset, 2)
    count = _u16(buf, offset, order)
    if count > _MAX_ENTRIES:
        raise _Corrupt(f"too many IFD entries: {count}")
    entries_start = offset + 2
    _check(buf, entries_start, count * 12)
    next_field = entries_start + count * 12
    _check(buf, next_field, 4)
    return entries_start, count, _u32(buf, next_field, order)


def _read_entry_value(buf: bytes, entry_off: int, order: str) -> tuple[int, int, int, bytes]:
    """Return `(tag, type_code, count, value_bytes)` for the entry at `entry_off`.

    `value_bytes` is already dereferenced if the value lives out-of-line.
    Unknown type codes or a zero count yield `b""` (caller treats that as
    "nothing to show" rather than guessing at an unknown byte size).
    """
    tag = _u16(buf, entry_off, order)
    type_code = _u16(buf, entry_off + 2, order)
    count = _u32(buf, entry_off + 4, order)
    type_size = _TYPE_SIZES.get(type_code)
    if type_size is None or count == 0:
        return tag, type_code, count, b""
    byte_length = count * type_size
    if byte_length <= 4:
        value_bytes = buf[entry_off + 8 : entry_off + 8 + byte_length]
    else:
        value_offset = _u32(buf, entry_off + 8, order)
        _check(buf, value_offset, byte_length)
        value_bytes = buf[value_offset : value_offset + byte_length]
    return tag, type_code, count, value_bytes


# TIFF type code -> struct format char, for the "numbers joined by ', '" detail branch.
_READ_NUMERIC_FMT = {1: "B", 3: "H", 4: "I", 6: "b", 8: "h", 9: "i", 11: "f", 12: "d"}


def _format_detail(type_code: int, count: int, value_bytes: bytes, order: str, tag: int) -> str | None:
    """Human-readable `Finding.detail` for one entry's already-dereferenced value.

    ASCII -> text up to the NUL; RATIONAL/SRATIONAL -> "n/d" pairs joined
    by ", "; SHORT/LONG (and other numeric types) -> numbers joined by
    ", "; UNDEFINED -> None, except UserComment, which is the text after
    its 8-byte charset header.
    """
    if type_code == 2:  # ASCII
        text = value_bytes.split(b"\x00", 1)[0]
        return text.decode("ascii", errors="replace")
    if type_code in (5, 10):  # RATIONAL / SRATIONAL
        fmt = "i" if type_code == 10 else "I"
        try:
            parts = [f"{num}/{den}" for num, den in struct.iter_unpack(order + fmt + fmt, value_bytes)]
        except struct.error:
            return None
        return ", ".join(parts)
    if type_code == 7:  # UNDEFINED
        if tag == 0x9286 and len(value_bytes) > 8:  # UserComment: charset header is 8 bytes
            return value_bytes[8:].decode("ascii", errors="replace")
        return None
    if type_code in _READ_NUMERIC_FMT:
        fmt = _READ_NUMERIC_FMT[type_code]
        try:
            values = struct.unpack_from(order + fmt * count, value_bytes, 0)
        except struct.error:
            return None
        return ", ".join(str(v) for v in values)
    return None


def _read_ifd(
    buf: bytes,
    offset: int,
    order: str,
    ifd_name: str,
    where: str,
    findings: list[Finding],
    visited: set[int],
) -> int:
    """Append one `Finding` per non-structural tag in the IFD at `offset`.

    Descends immediately into ExifIFD/GPS/Interop when their pointer tag
    is encountered, so findings from a sub-IFD are interleaved at the
    point their pointer appears in the parent. Returns this IFD's "next
    IFD" offset (0 if none), which the top-level `IFD0` uses to find the
    thumbnail IFD1.
    """
    entries_start, count, next_offset = _read_ifd_header(buf, offset, order, visited)
    for i in range(count):
        entry_off = entries_start + i * 12
        tag, type_code, entry_count, value_bytes = _read_entry_value(buf, entry_off, order)

        if tag in NO_FINDING_TAGS:
            sub_name = _POINTER_TARGETS.get(tag)
            if sub_name is not None and len(value_bytes) == 4:
                sub_offset = struct.unpack(order + "I", value_bytes)[0]
                _read_ifd(buf, sub_offset, order, sub_name, where, findings, visited)
            continue

        detail = _format_detail(type_code, entry_count, value_bytes, order, tag) if value_bytes else None
        label, category = _resolve(ifd_name, tag)
        findings.append(Finding(category, label, detail=detail, where=f"{where}/{ifd_name}"))

    return next_offset


def _parse(tiff: bytes, where: str) -> list[Finding]:
    order, ifd0_offset = _read_header(tiff)
    findings: list[Finding] = []
    visited: set[int] = set()

    next_offset = _read_ifd(tiff, ifd0_offset, order, "IFD0", where, findings, visited)

    if next_offset and next_offset + 2 <= len(tiff):
        findings.append(Finding(Category.EXTRAS, "Thumbnail (IFD1)", where=f"{where}/IFD1"))

    return findings


def parse_exif(tiff: bytes, where: str) -> list[Finding]:
    """Parse a big- or little-endian TIFF/EXIF blob into one `Finding` per tag.

    Never raises: any structural problem (offset out of bounds, IFD loop,
    more than 1000 entries in one IFD, or anything else unreadable)
    yields `[Finding(Category.UNKNOWN, "EXIF (unreadable)", where=where,
    size=len(tiff))]` instead.
    """
    try:
        return _parse(tiff, where)
    except Exception:
        return [Finding(Category.UNKNOWN, "EXIF (unreadable)", where=where, size=len(tiff))]


def strip_exif_header(data: bytes) -> bytes:
    """Remove the optional `Exif\\x00\\x00` prefix, returning `data` unchanged if absent."""
    prefix = b"Exif\x00\x00"
    if data.startswith(prefix):
        return data[len(prefix) :]
    return data


# ---------------------------------------------------------------------------
# Minimal EXIF writer
# ---------------------------------------------------------------------------

# Type-code groups for re-encoding a decoded value in the target byte order,
# per the writer's layout spec: 1/2/6/7 copy verbatim; 3/8 -> H/h; 4/9 ->
# I/i; 5/10 -> pairs of I/i; 11 -> f; 12 -> d.
_COPY_TYPES = frozenset({1, 2, 6, 7})
_SHORT_TYPE_FMT = {3: "H", 8: "h"}
_LONG_TYPE_FMT = {4: "I", 9: "i"}
_RATIONAL_TYPE_FMT = {5: "I", 10: "i"}


def _decode_values(type_code: int, count: int, value_bytes: bytes, order: str):
    """Decode `value_bytes` (in `order`) into a byte-order-neutral form.

    Copy types keep their raw bytes; numeric types become a tuple of
    Python numbers; RATIONAL/SRATIONAL become a tuple of `(num, den)`
    pairs. `_encode_values` reverses this into any target byte order.
    """
    if type_code in _COPY_TYPES:
        return value_bytes
    if type_code in _SHORT_TYPE_FMT:
        fmt = _SHORT_TYPE_FMT[type_code]
        return struct.unpack_from(order + fmt * count, value_bytes, 0)
    if type_code in _LONG_TYPE_FMT:
        fmt = _LONG_TYPE_FMT[type_code]
        return struct.unpack_from(order + fmt * count, value_bytes, 0)
    if type_code in _RATIONAL_TYPE_FMT:
        fmt = _RATIONAL_TYPE_FMT[type_code]
        flat = struct.unpack_from(order + fmt * (count * 2), value_bytes, 0)
        return tuple(zip(flat[0::2], flat[1::2]))
    if type_code == 11:
        return struct.unpack_from(order + "f" * count, value_bytes, 0)
    if type_code == 12:
        return struct.unpack_from(order + "d" * count, value_bytes, 0)
    return value_bytes


def _encode_values(type_code: int, count: int, decoded, order: str) -> bytes:
    if type_code in _COPY_TYPES:
        return decoded
    if type_code in _SHORT_TYPE_FMT:
        fmt = _SHORT_TYPE_FMT[type_code]
        return struct.pack(order + fmt * count, *decoded)
    if type_code in _LONG_TYPE_FMT:
        fmt = _LONG_TYPE_FMT[type_code]
        return struct.pack(order + fmt * count, *decoded)
    if type_code in _RATIONAL_TYPE_FMT:
        fmt = _RATIONAL_TYPE_FMT[type_code]
        flat = [v for pair in decoded for v in pair]
        return struct.pack(order + fmt * len(flat), *flat)
    if type_code == 11:
        return struct.pack(order + "f" * count, *decoded)
    if type_code == 12:
        return struct.pack(order + "d" * count, *decoded)
    return decoded if isinstance(decoded, bytes) else b""


def _collect_allowed(
    buf: bytes, entries_start: int, count: int, order: str, ifd_name: str, allowed: frozenset[Category]
) -> tuple[list[tuple[int, int, int, object]], int | None]:
    """Scan one IFD's entries for tags whose category is in `allowed`.

    Returns `(kept, exif_offset)`: `kept` is a list of `(tag, type_code,
    count, decoded_value)`, skipping every structural tag (`NO_FINDING_TAGS`);
    `exif_offset` is the source's `ExifIFDPointer` value when `ifd_name` is
    `"IFD0"` and one was present, else `None`.
    """
    kept: list[tuple[int, int, int, object]] = []
    exif_offset: int | None = None
    for i in range(count):
        entry_off = entries_start + i * 12
        tag, type_code, entry_count, value_bytes = _read_entry_value(buf, entry_off, order)
        if ifd_name == "IFD0" and tag == 0x8769 and len(value_bytes) == 4:
            exif_offset = struct.unpack(order + "I", value_bytes)[0]
            continue
        if tag in NO_FINDING_TAGS or not value_bytes:
            continue
        _, category = _resolve(ifd_name, tag)
        if category in allowed:
            kept.append((tag, type_code, entry_count, _decode_values(type_code, entry_count, value_bytes, order)))
    return kept, exif_offset


def _ifd_size(entries: list[tuple[int, int, int, object]], order: str) -> int:
    size = 2 + 12 * len(entries) + 4
    for _tag, type_code, count, value in entries:
        if value is None:  # pointer placeholder: LONG, count 1, always inline
            continue
        encoded = _encode_values(type_code, count, value, order)
        if len(encoded) > 4:
            size += len(encoded) + (len(encoded) % 2)
    return size


def _emit_ifd(
    entries: list[tuple[int, int, int, object]],
    order: str,
    start_offset: int,
    next_offset: int,
    pointer_targets: dict[int, int],
) -> bytes:
    header_size = 2 + 12 * len(entries) + 4
    voffset = start_offset + header_size
    head = bytearray(struct.pack(order + "H", len(entries)))
    tail = bytearray()
    for tag, type_code, count, value in entries:
        head += struct.pack(order + "HH", tag, type_code)
        head += struct.pack(order + "I", count)
        if value is None:
            head += struct.pack(order + "I", pointer_targets[tag])
            continue
        encoded = _encode_values(type_code, count, value, order)
        if len(encoded) <= 4:
            head += encoded + b"\x00" * (4 - len(encoded))
        else:
            head += struct.pack(order + "I", voffset)
            padded = encoded + (b"\x00" if len(encoded) % 2 else b"")
            tail += padded
            voffset += len(padded)
    head += struct.pack(order + "I", next_offset)
    return bytes(head) + bytes(tail)


def _write_minimal(
    ifd0_kept: list[tuple[int, int, int, object]], exif_kept: list[tuple[int, int, int, object]]
) -> bytes:
    order = ">"
    include_exif = bool(exif_kept)

    ifd0_entries = list(ifd0_kept)
    if include_exif:
        ifd0_entries.append((0x8769, 4, 1, None))
    ifd0_entries.sort(key=lambda e: e[0])

    exif_entries: list[tuple[int, int, int, object]] = []
    if include_exif:
        exif_entries.append((0x9000, 7, 4, b"0232"))
        exif_entries.extend(exif_kept)
        exif_entries.sort(key=lambda e: e[0])

    ifd0_offset = 8
    exif_offset = ifd0_offset + _ifd_size(ifd0_entries, order) if include_exif else None

    buf = bytearray(b"MM\x00\x2a")
    buf += struct.pack(">I", ifd0_offset)
    pointer_targets = {0x8769: exif_offset} if include_exif else {}
    buf += _emit_ifd(ifd0_entries, order, ifd0_offset, 0, pointer_targets)
    if include_exif:
        buf += _emit_ifd(exif_entries, order, exif_offset, 0, {})
    return bytes(buf)


def _build_minimal(tiff: bytes, allowed: frozenset[Category]) -> bytes | None:
    order, ifd0_offset = _read_header(tiff)
    visited: set[int] = set()

    entries_start, count, _next = _read_ifd_header(tiff, ifd0_offset, order, visited)
    ifd0_kept, exif_offset = _collect_allowed(tiff, entries_start, count, order, "IFD0", allowed)

    exif_kept: list[tuple[int, int, int, object]] = []
    if exif_offset is not None:
        exif_entries_start, exif_count, _next = _read_ifd_header(tiff, exif_offset, order, visited)
        exif_kept, _ = _collect_allowed(tiff, exif_entries_start, exif_count, order, "ExifIFD", allowed)

    if not ifd0_kept and not exif_kept:
        return None
    return _write_minimal(ifd0_kept, exif_kept)


def build_minimal_exif(tiff: bytes, allowed: frozenset[Category]) -> bytes | None:
    """Build a new, minimal big-endian TIFF with only `allowed` categories.

    Only IFD0 and ExifIFD are ever emitted (GPS/Interop/the thumbnail are
    never carried over, regardless of `allowed`). `ExifIFDPointer` and
    `ExifVersion` are generated fresh; any such tag copied from the
    source is ignored. Returns `None` if nothing is left to keep, or if
    `tiff` is unreadable.
    """
    try:
        return _build_minimal(tiff, allowed)
    except Exception:
        return None
