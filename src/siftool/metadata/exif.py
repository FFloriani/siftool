"""EXIF/TIFF reading, per-tag privacy categories, and a minimal EXIF writer.

`parse_exif` walks a TIFF byte blob (the payload of a JPEG APP1 "Exif"
segment, or a bare TIFF file) and returns one `Finding` per tag, tagged
with the `Category` a privacy mode can whitelist. `build_minimal_exif`
writes a brand-new, minimal big-endian TIFF containing only the tags
whose category is allowed -- used to keep e.g. `Orientation` while
dropping GPS. `strip_exif_header` removes the optional `Exif\\x00\\x00`
prefix some containers (JPEG APP1) put before the TIFF bytes.

Every tag not covered by `TAG_CATEGORIES` (or the GPS/Interop IFDs, which
have their own rules) is `Category.UNKNOWN`, labelled `f"Tag 0x{tag:04X}"`.
A fixed set of *structural* tags -- the sub-IFD pointers, the thumbnail
offset/length, and `ExifVersion` (generated by `build_minimal_exif` itself)
-- never produce a `Finding` at all (ruling R6).

Robustness is a hard requirement: malformed input (bad offsets, IFD
loops, oversized entry counts, truncated values) must never raise. Every
public function bottoms out in a broad `except Exception` that degrades
to a single `Finding` (`parse_exif`) or `None` (`build_minimal_exif`).
"""

from __future__ import annotations

import struct

from ..model import Category, Finding

_MAX_ENTRIES = 1000

# TIFF type code -> byte size of one value.
_TYPE_SIZES = {1: 1, 2: 1, 3: 2, 4: 4, 5: 8, 6: 1, 7: 1, 8: 2, 9: 4, 10: 8, 11: 4, 12: 8}

