_MAX_ASCII = 128  # bytes, NUL included (ruling R18)
_ORIENTATION = 0x0112

# The Exif 2.32 (CIPA DC-008-2019) type and count of every tag a mode can
# allow (appearance, device, camera_settings): `tag -> (type, min_count,
# max_count)`. The writer keeps an allowed tag only in exactly this form;
# anything else -- an Orientation typed ASCII, a YResolution carrying a
# bit-flipped Artist string, a SHORT typed LONG -- is dropped (ruling R18).
# Where the standard leaves the count open ("Any"), the bound used here is
# noted on the entry. Orientation must also hold a value from 1 to 8.
STANDARD_FORMS: dict[int, tuple[int, int, int]] = {
    # appearance
    0x0112: (_SHORT, 1, 1),  # Orientation
    0x011A: (_RATIONAL, 1, 1),  # XResolution
    0x011B: (_RATIONAL, 1, 1),  # YResolution
    0x0128: (_SHORT, 1, 1),  # ResolutionUnit
    0xA001: (_SHORT, 1, 1),  # ColorSpace
    0xA500: (_RATIONAL, 1, 1),  # Gamma
    # device (ASCII count "Any" in the standard; at most 128 bytes here)
    0x010F: (_ASCII, 1, _MAX_ASCII),  # Make
    0x0110: (_ASCII, 1, _MAX_ASCII),  # Model
    0xA432: (_RATIONAL, 4, 4),  # LensSpecification
    0xA433: (_ASCII, 1, _MAX_ASCII),  # LensMake
    0xA434: (_ASCII, 1, _MAX_ASCII),  # LensModel
    # camera_settings
    0x829A: (_RATIONAL, 1, 1),  # ExposureTime
    0x829D: (_RATIONAL, 1, 1),  # FNumber
    0x8822: (_SHORT, 1, 1),  # ExposureProgram
    0x8827: (_SHORT, 1, 3),  # PhotographicSensitivity: count "Any"; ISO 12232 speed + latitude yy, zz
    0x8830: (_SHORT, 1, 1),  # SensitivityType
    0x9201: (_SRATIONAL, 1, 1),  # ShutterSpeedValue
    0x9202: (_RATIONAL, 1, 1),  # ApertureValue
    0x9203: (_SRATIONAL, 1, 1),  # BrightnessValue
    0x9204: (_SRATIONAL, 1, 1),  # ExposureBiasValue
    0x9205: (_RATIONAL, 1, 1),  # MaxApertureValue
    0x9207: (_SHORT, 1, 1),  # MeteringMode
    0x9208: (_SHORT, 1, 1),  # LightSource
    0x9209: (_SHORT, 1, 1),  # Flash
    0x920A: (_RATIONAL, 1, 1),  # FocalLength
    0xA402: (_SHORT, 1, 1),  # ExposureMode
    0xA403: (_SHORT, 1, 1),  # WhiteBalance
    0xA404: (_RATIONAL, 1, 1),  # DigitalZoomRatio
    0xA405: (_SHORT, 1, 1),  # FocalLengthIn35mmFilm
    0xA406: (_SHORT, 1, 1),  # SceneCaptureType
    0xA408: (_SHORT, 1, 1),  # Contrast
    0xA409: (_SHORT, 1, 1),  # Saturation
    0xA40A: (_SHORT, 1, 1),  # Sharpness
}

# struct format of one value of each numeric type STANDARD_FORMS uses.
_VALUE_FMT = {_SHORT: "H", _RATIONAL: "II", _SRATIONAL: "ii"}

# A writer entry: (tag, type, count, big-endian value bytes), or value None
# for the ExifIFD pointer, whose offset is only known at layout time.
_Entry = tuple[int, int, int, "bytes | None"]


def _canonical_entry(tag: int, type_code: int, count: int, value_bytes: bytes, order: str) -> _Entry | None:
    """`tag`'s value in canonical big-endian form, or None if it isn't in its `STANDARD_FORMS` form.

    ASCII is cut at its first NUL (one NUL-terminated string, nothing
    after it); numbers are re-packed big-endian. The result is itself a
    standard form, which is what makes the writer a fixed point.
    """
    form = STANDARD_FORMS.get(tag)
    if form is None:
        return None
    std_type, min_count, max_count = form
    if type_code != std_type or not min_count <= count <= max_count:
        return None
    if std_type == _ASCII:
        text = value_bytes.split(b"\x00", 1)[0] + b"\x00"
        return (tag, _ASCII, len(text), text) if len(text) <= _MAX_ASCII else None
    fmt = _VALUE_FMT[std_type] * count
    values = struct.unpack(order + fmt, value_bytes)
    if tag == _ORIENTATION and not 1 <= values[0] <= 8:
        return None
    return tag, std_type, count, struct.pack(">" + fmt, *values)


def _collect_allowed(
    buf: bytes, entries_start: int, count: int, order: str, ifd_name: str, allowed: frozenset[Category]
) -> tuple[list[_Entry], int | None]:
    """Scan one IFD's entries for allowed tags in their standard form.

    Returns `(kept, exif_offset)`: `kept` lists the canonical entry
    (`_canonical_entry`) of every tag that belongs to `ifd_name`'s OWN
    table (`IFD0` -> `_IFD0_TAGS`, `ExifIFD` -> `_EXIF_IFD_TAGS`; unlike
    `_resolve`, there is no fallback to the other main IFD's table here),
    whose category is in `allowed` and whose type/count match
    `STANDARD_FORMS`, skipping every structural tag (`NO_FINDING_TAGS`). A
    tag found only in the "wrong" main IFD is never kept -- a reader such
    as Pillow looks for it in its home IFD only, so keeping it there would
    be silent dead weight at best (re-review of the fix wave). `exif_offset`
    is the ExifIFD pointer's value when `ifd_name` is `"IFD0"` and it holds
    one in a followable form (`_pointer_offset`), else `None`. Only the
    FIRST entry of each tag counts -- TIFF forbids repeating one in an IFD
    -- so every later entry with the same tag is ignored, even when the
    first is not kept (ruling R24: N copies of an allowed tag would
    otherwise carry N values of free bytes). Every non-pointer value, a
    repeated one included, is bounds-checked exactly as `parse_exif` checks
    it, but no more than `_MAX_ASCII` bytes of it are copied -- no standard
    form is longer.
    """
    kept: list[_Entry] = []
    exif_offset: int | None = None
    seen: set[int] = set()
    home = _IFD0_TAGS if ifd_name == "IFD0" else _EXIF_IFD_TAGS
    for i in range(count):
        entry_off = entries_start + i * 12
        tag = _u16(buf, entry_off, order)
        first = tag not in seen
        seen.add(tag)
        if tag in _POINTER_TARGETS:
            if first and ifd_name == "IFD0" and tag == 0x8769:
                exif_offset = _pointer_offset(buf, entry_off, order)
            continue
        _, type_code, entry_count, value_bytes = _read_entry_value(buf, entry_off, order, _MAX_ASCII)
        if not first or tag in NO_FINDING_TAGS or not value_bytes or tag not in home:
            continue
        _, category = home[tag]
        if category in allowed:
            entry = _canonical_entry(tag, type_code, entry_count, value_bytes, order)
            if entry is not None:
                kept.append(entry)
    return kept, exif_offset


def _ifd_size(entries: list[_Entry]) -> int:
    size = 2 + 12 * len(entries) + 4
    for _tag, _type, _count, value in entries:
        if value is not None and len(value) > 4:  # None: the pointer, always inline
            size += len(value) + len(value) % 2
    return size


def _emit_ifd(entries: list[_Entry], start_offset: int, pointer_targets: dict[int, int]) -> bytes:
    """One big-endian IFD at `start_offset`, out-of-line values right after it, next IFD 0."""
    voffset = start_offset + 2 + 12 * len(entries) + 4
    head = bytearray(struct.pack(">H", len(entries)))
    tail = bytearray()
    for tag, type_code, count, value in entries:
        head += struct.pack(">HHI", tag, type_code, count)
        if value is None:
            head += struct.pack(">I", pointer_targets[tag])
        elif len(value) <= 4:
            head += value.ljust(4, b"\x00")
        else:
            head += struct.pack(">I", voffset)
            padded = value + (b"\x00" if len(value) % 2 else b"")
            tail += padded
            voffset += len(padded)
    head += struct.pack(">I", 0)
    return bytes(head) + bytes(tail)


def _write_minimal(ifd0_kept: list[_Entry], exif_kept: list[_Entry]) -> bytes:
    include_exif = bool(exif_kept)

    ifd0_entries = list(ifd0_kept)
    if include_exif:
        ifd0_entries.append((0x8769, _LONG, 1, None))
    ifd0_entries.sort(key=lambda e: e[0])

    exif_entries: list[_Entry] = []
    if include_exif:
        exif_entries.append((0x9000, _UNDEFINED, 4, b"0232"))
        exif_entries.extend(exif_kept)
        exif_entries.sort(key=lambda e: e[0])

    ifd0_offset = 8
    buf = bytearray(b"MM\x00\x2a") + struct.pack(">I", ifd0_offset)
    if not include_exif:
        return bytes(buf + _emit_ifd(ifd0_entries, ifd0_offset, {}))
    exif_offset = ifd0_offset + _ifd_size(ifd0_entries)
    buf += _emit_ifd(ifd0_entries, ifd0_offset, {0x8769: exif_offset})
    buf += _emit_ifd(exif_entries, exif_offset, {})
    return bytes(buf)


def _build_minimal(tiff: bytes, allowed: frozenset[Category]) -> bytes | None:
    order, ifd0_offset = _read_header(tiff)
    visited: set[int] = set()

    entries_start, count, _next = _read_ifd_header(tiff, ifd0_offset, order, visited)
    ifd0_kept, exif_offset = _collect_allowed(tiff, entries_start, count, order, "IFD0", allowed)

    exif_kept: list[_Entry] = []
    if exif_offset is not None:
        exif_entries_start, exif_count, _next = _read_ifd_header(tiff, exif_offset, order, visited)
        exif_kept, _ = _collect_allowed(tiff, exif_entries_start, exif_count, order, "ExifIFD", allowed)

    if not ifd0_kept and not exif_kept:
        return None
    return _write_minimal(ifd0_kept, exif_kept)


def build_minimal_exif(tiff: bytes, allowed: frozenset[Category]) -> bytes | None:
    """Build a new, minimal big-endian TIFF with only `allowed` categories.

    Only IFD0 and ExifIFD are ever emitted (GPS/Interop/the thumbnails --
    IFD1's or one referenced from IFD0 -- and any bytes no kept entry
    references are never carried over, regardless of `allowed`). An
    allowed tag survives only from its first entry in its IFD (a repeat
    is ignored, ruling R24) and only in its `STANDARD_FORMS` type and
    count, in canonical form (`_canonical_entry`); the ExifIFD is the one
    IFD0's first ExifIFD pointer leads to. `ExifIFDPointer` and
    `ExifVersion` are generated fresh, and any such tag in the source is
    ignored. The output is a fixed point of this function for the same
    `allowed`.
    Returns `None` if nothing is left to keep, or if `tiff` is unreadable
    (including an ExifIFD that cannot be read).
    """
    try:
        return _build_minimal(tiff, allowed)
    except Exception:
        return None
