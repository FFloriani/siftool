def _resolve(ifd_name: str, tag: int) -> tuple[str, Category]:
    """Return `(label, category)` for `tag` found while parsing `ifd_name`.

    IFD0/ExifIFD tags fall back to the other main IFD's table when absent
    from their own (addendum rule); GPS tags are always `LOCATION`;
    Interop tags are always `UNKNOWN`. Anything still unmatched is
    `UNKNOWN`, labelled `f"Tag 0x{tag:04X}"`.
    """
    if ifd_name == "GPS":
        return _GPS_TAG_NAMES.get(tag, f"Tag 0x{tag:04X}"), Category.LOCATION
    if ifd_name == "Interop":
        return f"Tag 0x{tag:04X}", Category.UNKNOWN
    primary = _IFD0_TAGS if ifd_name == "IFD0" else _EXIF_IFD_TAGS
    fallback = _EXIF_IFD_TAGS if ifd_name == "IFD0" else _IFD0_TAGS
    if tag in primary:
        return primary[tag]
    if tag in fallback:
        return fallback[tag]
    return f"Tag 0x{tag:04X}", Category.UNKNOWN


class _Corrupt(Exception):
    """Raised internally on any structural problem; never escapes this module."""


def _check(buf: bytes, offset: int, length: int) -> None:
    if offset < 0 or length < 0 or offset + length > len(buf):
        raise _Corrupt(f"out of bounds: offset={offset} length={length} buf={len(buf)}")


def _u16(buf: bytes, offset: int, order: str) -> int:
    return struct.unpack_from(order + "H", buf, offset)[0]


def _u32(buf: bytes, offset: int, order: str) -> int:
    return struct.unpack_from(order + "I", buf, offset)[0]


def _read_header(tiff: bytes) -> tuple[str, int]:
    """Return `(byte_order, ifd0_offset)`, or raise `_Corrupt`."""
    _check(tiff, 0, 8)
    bom = tiff[0:2]
    if bom == b"II":
        order = "<"
    elif bom == b"MM":
        order = ">"
    else:
        raise _Corrupt(f"bad byte order mark: {bom!r}")
    if _u16(tiff, 2, order) != 0x2A:
        raise _Corrupt("bad TIFF magic number")
    return order, _u32(tiff, 4, order)


def _read_ifd_header(buf: bytes, offset: int, order: str, visited: set[int]) -> tuple[int, int, int]:
    """Bounds-check `offset` as an IFD header; return `(entries_start, count, next_offset)`.

    Marks `offset` visited (raising `_Corrupt` if already visited, which
    is how IFD loops are detected) and rejects more than `_MAX_ENTRIES`.
    """
    if offset in visited:
        raise _Corrupt(f"IFD loop at offset {offset}")
    visited.add(offset)
    _check(buf, offset, 2)
    count = _u16(buf, offset, order)
    if count > _MAX_ENTRIES:
        raise _Corrupt(f"too many IFD entries: {count}")
    entries_start = offset + 2
    _check(buf, entries_start, count * 12)
    next_field = entries_start + count * 12
    _check(buf, next_field, 4)
    return entries_start, count, _u32(buf, next_field, order)


def _read_entry_value(
    buf: bytes, entry_off: int, order: str, limit: int | None = None
) -> tuple[int, int, int, bytes]:
    """Return `(tag, type_code, count, value_bytes)` for the entry at `entry_off`.

    `value_bytes` is already dereferenced if the value lives out-of-line.
    The whole value is always bounds-checked, but with `limit` only its
    first `limit` bytes are copied -- describing a tag never needs more,
    however large its count (review M5). Unknown type codes or a zero
    count yield `b""` (caller treats that as "nothing to show" rather than
    guessing at an unknown byte size).
    """
    tag = _u16(buf, entry_off, order)
    type_code = _u16(buf, entry_off + 2, order)
    count = _u32(buf, entry_off + 4, order)
    type_size = _TYPE_SIZES.get(type_code)
    if type_size is None or count == 0:
        return tag, type_code, count, b""
    byte_length = count * type_size
    if byte_length <= 4:
        start = entry_off + 8
    else:
        start = _u32(buf, entry_off + 8, order)
        _check(buf, start, byte_length)
    if limit is not None:
        byte_length = min(byte_length, limit)
    return tag, type_code, count, buf[start : start + byte_length]


def _pointer_offset(buf: bytes, entry_off: int, order: str) -> int | None:
    """The sub-IFD offset held by the pointer entry at `entry_off`, or None.

    Only a count of 1 stored as `LONG`, `IFD` (type 13) or `SHORT` is a
    pointer this module follows -- each fits inline in the entry's own
    4-byte field. Any other type (e.g. BigTIFF's LONG8/IFD8) or count is
    None: not followed, and reported by the caller (ruling R18).
    """
    type_code = _u16(buf, entry_off + 2, order)
    if _u32(buf, entry_off + 4, order) != 1:
        return None
    if type_code in (_LONG, _IFD):
        return _u32(buf, entry_off + 8, order)
    if type_code == _SHORT:
        return _u16(buf, entry_off + 8, order)
    return None


# TIFF type code -> struct format char, for the "numbers joined by ', '" detail branch.
_READ_NUMERIC_FMT = {1: "B", 3: "H", 4: "I", 6: "b", 8: "h", 9: "i", 11: "f", 12: "d"}


def _joined(parts: list[str], count: int) -> str:
    """`parts` joined by ", ", plus ", ..." when `count` values exist beyond them."""
    text = ", ".join(parts)
    return text + ", ..." if count > len(parts) else text


def _format_detail(type_code: int, count: int, value_bytes: bytes, order: str, tag: int) -> str | None:
    """Human-readable `Finding.detail` for one entry's already-dereferenced value.

    ASCII -> text up to the NUL; RATIONAL/SRATIONAL -> "n/d" pairs joined
    by ", "; SHORT/LONG (and other numeric types) -> numbers joined by
    ", "; UNDEFINED -> None, except UserComment, which is the text after
    its 8-byte charset header. Only the first `_MAX_DETAIL_VALUES` values
    (80 bytes of text) are ever read -- ", ..." marks that more exist --
    since `Finding` cuts every detail at 80 characters anyway (review M5).
    """
    shown = min(count, _MAX_DETAIL_VALUES)
    if type_code == _ASCII:
        return value_bytes[:80].split(b"\x00", 1)[0].decode("ascii", errors="replace")
    if type_code in (_RATIONAL, _SRATIONAL):
        fmt = "i" if type_code == _SRATIONAL else "I"
        try:
            flat = struct.unpack_from(order + fmt * (2 * shown), value_bytes, 0)
        except struct.error:
            return None
        return _joined([f"{num}/{den}" for num, den in zip(flat[0::2], flat[1::2])], count)
    if type_code == _UNDEFINED:
        if tag == 0x9286 and len(value_bytes) > 8:  # UserComment: charset header is 8 bytes
            return value_bytes[8:88].decode("ascii", errors="replace")
        return None
    if type_code in _READ_NUMERIC_FMT:
        fmt = _READ_NUMERIC_FMT[type_code]
        try:
            values = struct.unpack_from(order + fmt * shown, value_bytes, 0)
        except struct.error:
            return None
        return _joined([str(v) for v in values], count)
    return None


def _read_ifd(
    buf: bytes,
    offset: int,
    order: str,
    ifd_name: str,
    where: str,
    findings: list[Finding],
    visited: set[int],
) -> int:
    """Append one `Finding` per non-structural tag in the IFD at `offset`.

    Descends immediately into ExifIFD/GPS/Interop when their pointer tag
    is encountered, so findings from a sub-IFD are interleaved at the
    point their pointer appears in the parent. A pointer that cannot be
    followed -- `_pointer_offset` rejects its form, or reading the sub-IFD
    fails anywhere (out of bounds, a loop, too many entries, a value out
    of bounds) -- appends `Finding(UNKNOWN, UNFOLLOWED_POINTER, None,
    f"{where}/{ifd_name}", len(buf))` after whatever the sub-IFD yielded
    before failing, and parsing goes on (ruling R18). TIFF forbids a tag
    twice in one IFD: every entry repeating a tag already seen in this IFD
    -- a pointer or a structural tag included -- only appends
    `Finding(UNKNOWN, f"Duplicate tag 0x{tag:04X}", None,
    f"{where}/{ifd_name}", <its value's byte length>)` and is neither
    described nor followed (ruling R24). Returns this IFD's "next IFD"
    offset (0 if none), which the top-level `IFD0` uses to find the
    thumbnail IFD1.
    """
    entries_start, count, next_offset = _read_ifd_header(buf, offset, order, visited)
    seen: set[int] = set()
    for i in range(count):
        entry_off = entries_start + i * 12
        tag = _u16(buf, entry_off, order)

        if tag in seen:
            _, type_code, entry_count, _ = _read_entry_value(buf, entry_off, order, 0)  # bounds-checked all the same
            size = entry_count * _TYPE_SIZES.get(type_code, 0)
            findings.append(Finding(Category.UNKNOWN, f"Duplicate tag 0x{tag:04X}", None, f"{where}/{ifd_name}", size))
            continue
        seen.add(tag)

        sub_name = _POINTER_TARGETS.get(tag)
        if sub_name is not None:
            sub_offset = _pointer_offset(buf, entry_off, order)
            try:
                if sub_offset is None:
                    raise _Corrupt(f"pointer 0x{tag:04X} is not LONG/SHORT/IFD with count 1")
                _read_ifd(buf, sub_offset, order, sub_name, where, findings, visited)
            except _Corrupt:
                findings.append(
                    Finding(Category.UNKNOWN, UNFOLLOWED_POINTER, None, f"{where}/{ifd_name}", len(buf))
                )
            continue

        _, type_code, entry_count, value_bytes = _read_entry_value(buf, entry_off, order, _MAX_DETAIL_BYTES)
        if tag in NO_FINDING_TAGS:
            continue
        detail = _format_detail(type_code, entry_count, value_bytes, order, tag) if value_bytes else None
        label, category = _resolve(ifd_name, tag)
        findings.append(Finding(category, label, detail=detail, where=f"{where}/{ifd_name}"))

    return next_offset


def _parse(tiff: bytes, where: str) -> list[Finding]:
    order, ifd0_offset = _read_header(tiff)
    findings: list[Finding] = []
    visited: set[int] = set()

    next_offset = _read_ifd(tiff, ifd0_offset, order, "IFD0", where, findings, visited)

    if next_offset and next_offset + 2 <= len(tiff):
        findings.append(Finding(Category.EXTRAS, "Thumbnail (IFD1)", where=f"{where}/IFD1"))

    return findings


def parse_exif(tiff: bytes, where: str) -> list[Finding]:
    """Parse a big- or little-endian TIFF/EXIF blob into one `Finding` per tag.

    Never raises: any structural problem in the header or IFD0 (offset out
    of bounds, IFD loop, more than 1000 entries in one IFD, or anything
    else unreadable) yields `[Finding(Category.UNKNOWN, "EXIF (unreadable)",
    where=where, size=len(tiff))]` instead. A sub-IFD that cannot be
    followed does not spoil the rest: it adds one `Finding(Category.UNKNOWN,
    "Unfollowed sub-IFD pointer", None, f"{where}/<IFD>", len(tiff))`. A tag
    repeated in one IFD yields its first entry's finding, then one
    `Finding(Category.UNKNOWN, f"Duplicate tag 0x{tag:04X}", None,
    f"{where}/<IFD>", <value byte length>)` per repeat (ruling R24).
    """
    try:
        return _parse(tiff, where)
    except Exception:
        return [Finding(Category.UNKNOWN, "EXIF (unreadable)", where=where, size=len(tiff))]


def strip_exif_header(data: bytes) -> bytes:
    """Remove the optional `Exif\\x00\\x00` prefix, returning `data` unchanged if absent."""
    prefix = b"Exif\x00\x00"
    if data.startswith(prefix):
        return data[len(prefix) :]
    return data


